-- Medication catalog. The application validates and normalises every field
-- (internal/medication), but the database enforces the same invariants with
-- CHECK constraints so no code path (or manual fix) can store invalid rows.
CREATE TABLE medications (
    id               uuid          PRIMARY KEY,           -- UUIDv7, generated by the app
    name             text          NOT NULL CHECK (char_length(name) BETWEEN 1 AND 200),
    dosage_value     numeric(12,4) NOT NULL CHECK (dosage_value > 0),
    dosage_unit      text          NOT NULL CHECK (dosage_unit IN ('mg', 'mcg', 'g', 'mL', 'IU', '%')),
    dosage_per_value numeric(12,4)          CHECK (dosage_per_value > 0),
    dosage_per_unit  text                   CHECK (dosage_per_unit IN ('mg', 'mcg', 'g', 'mL', 'IU')),
    -- text + CHECK instead of a Postgres ENUM: adding a value later is a
    -- simple constraint swap, and ENUM values can never be removed.
    form             text          NOT NULL CHECK (form IN ('tablet', 'capsule', 'liquid')),
    version          bigint        NOT NULL DEFAULT 1 CHECK (version >= 1),
    created_at       timestamptz   NOT NULL DEFAULT now(),
    updated_at       timestamptz   NOT NULL DEFAULT now(),
    deleted_at       timestamptz,  -- soft delete: NULL = active

    CONSTRAINT medications_dosage_per_both_or_neither
        CHECK ((dosage_per_value IS NULL) = (dosage_per_unit IS NULL)),
    CONSTRAINT medications_dosage_per_is_concentration
        CHECK (dosage_per_unit IS NULL OR (dosage_unit <> '%' AND dosage_per_unit <> dosage_unit))
);

-- One active medication per (name ignoring case, dosage, form). Partial index:
-- soft-deleted rows don't count, so a deleted product can be re-created.
-- NULLS NOT DISTINCT (PostgreSQL 15+): without it two "500 mg" rows (both with
-- NULL per_value/per_unit) would never conflict, because NULL <> NULL.
CREATE UNIQUE INDEX medications_active_identity_key
    ON medications (lower(name), dosage_value, dosage_unit, dosage_per_value, dosage_per_unit, form)
    NULLS NOT DISTINCT
    WHERE deleted_at IS NULL;

